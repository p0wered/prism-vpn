/**
 * Шейдер светового ядра кнопки подключения (PROJECT.md → «Мок мобильного
 * приложения»). Вынесен из компонента отдельно: GLSL длиннее самой обвязки,
 * вперемешку с JSX его невозможно читать.
 *
 * Принцип — «цвет живёт в свете»: никакого акцентного цвета, только белое
 * ядро с холодным спадом. Холод берётся не подмешиванием синего в белое,
 * а дисперсией: три канала считаются на слегка разных радиусах, красный
 * гаснет раньше синего. Физика стекла, а не покраска.
 */

export const coreVert = `
attribute vec2 position;
attribute vec2 uv;
varying vec2 vUv;
void main() {
  vUv = uv;
  gl_Position = vec4(position, 0.0, 1.0);
}`

export const coreFrag = `precision highp float;

uniform vec2  uResolution;
uniform float uTime;
uniform float uOn;    // 0 — отключено, 1 — подключено (плавно едет между)
uniform float uBusy;  // 0..1 — разгон турбулентности на переходных фазах
uniform float uWave;  // 0..1 — прогресс ударной волны, вне (0,1) волны нет
uniform vec3  uIce;
uniform vec3  uBeam;

varying vec2 vUv;

float hash(vec2 p) {
  return fract(sin(dot(p, vec2(127.1, 311.7))) * 43758.5453123);
}

float noise(vec2 p) {
  vec2 i = floor(p);
  vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(
    mix(hash(i + vec2(0.0, 0.0)), hash(i + vec2(1.0, 0.0)), u.x),
    mix(hash(i + vec2(0.0, 1.0)), hash(i + vec2(1.0, 1.0)), u.x),
    u.y
  );
}

float fbm(vec2 p) {
  float v = 0.0;
  float a = 0.5;
  for (int i = 0; i < 4; i++) {
    v += a * noise(p);
    p *= 2.02;
    a *= 0.5;
  }
  return v;
}

/* Мягкое плечо вместо гауссианы: степень 1.5 даёт плотное ядро и длинный спад */
float core(float r, float radius) {
  return exp(-pow(max(r, 0.0) / radius, 1.5) * 2.2);
}

void main() {
  /* Нормализация по короткой стороне — ядро остаётся круглым на любом канвасе */
  vec2 p = (vUv * 2.0 - 1.0) * (uResolution / min(uResolution.x, uResolution.y));
  float r = length(p);
  float ang = atan(p.y, p.x);
  float t = uTime;

  /*
   * Дыхание. Выключенным — медленное и глубокое (ядро «спит»), подключённым —
   * частое и мелкое: живое, но не дёргается под таймером сессии.
   */
  float breathe = mix(
    0.86 + 0.14 * sin(t * 0.55),
    0.97 + 0.03 * sin(t * 1.15),
    uOn
  );

  /*
   * Домен-варп радиуса: fbm даёт неровность кромки, угловой шум — медленные
   * протуберанцы внутри ядра. На переходных фазах оба усиливаются (uBusy).
   */
  float turb  = fbm(p * 2.2 + vec2(t * 0.14, -t * 0.11)) - 0.5;
  float swirl = fbm(vec2(ang * 1.6, r * 3.4 - t * 0.30)) - 0.5;
  float rw = max(r + (turb * 0.9 + swirl * 0.6) * (0.10 + 0.16 * uBusy + 0.05 * uOn), 0.0);

  /*
   * Радиус подобран так, чтобы ядро было ШИРЕ диска кнопки (его радиус —
   * ~0.53 в этих координатах). Иначе весь свет остаётся под матовым стеклом,
   * наружу не выходит ничего, и кнопка читается как металлический шар,
   * а не как источник света.
   */
  float radius = mix(0.26, 0.50, uOn) * breathe;

  /*
   * Дисперсия: красный канал считается на большем радиусе (гаснет раньше),
   * синий — на меньшем (уходит дальше). В центре все три в единице — белое
   * ядро; к краю остаётся холодный спад.
   */
  float d = 0.030 * mix(0.6, 1.0, uOn);
  vec3 col = vec3(
    core(rw + d, radius),
    core(rw,     radius),
    core(rw - d, radius)
  );

  /* Раскалённый центр — выбитый в белое, источник всего света */
  col += vec3(exp(-pow(rw / (radius * 0.42), 2.0)) * mix(0.30, 1.15, uOn));

  /* Холодный ореол и глубокий синий в дальнем спаде — beam только здесь */
  col += uIce  * exp(-pow(rw / (radius * 2.4), 2.0)) * (0.04 + 0.22 * uOn);
  col += uBeam * exp(-rw * 2.6) * (0.10 + 0.22 * uOn);

  /*
   * Широкая слабая засветка: подключённая кнопка подсвечивает сам экран
   * вокруг себя. Без неё свет обрывается о кромку диска и вся композиция
   * читается как жемчужина на чёрном, а не как источник.
   */
  col += uIce * exp(-pow(rw / 2.2, 2.0)) * 0.05 * uOn;

  /*
   * Выключенное ядро едва тлеет. На переходных фазах приподнимаем яркость:
   * иначе «connecting» отличается от «off» только бегущей дугой, и кадр
   * не читается как разгон.
   */
  col *= mix(mix(0.35, 0.62, uBusy), 1.0, uOn);

  /*
   * Ударная волна: тонкое кольцо, уходящее за пределы кнопки и гаснущее.
   * Складывается ПОСЛЕ множителя состояния — это событие, а не состояние:
   * до множителя вспышка от нажатия гасла ровно там, где должна быть ярче
   * всего, потому что ядро в этот момент ещё не разгорелось.
   */
  if (uWave > 0.0001 && uWave < 1.0) {
    float ring = exp(-pow((r - uWave * 1.55) / 0.055, 2.0));
    col += mix(uIce, vec3(1.0), 0.55) * ring * pow(1.0 - uWave, 1.7) * 1.8;
  }

  /*
   * Гашение кромок канваса (PROJECT.md → «Правило кромок»): широкая засветка
   * иначе доходит до краёв прямоугольника и обрывается прямой линией — на
   * чёрном фоне этот стык читается как шов под шапкой.
   *
   * Маска эллиптическая, по форме канваса, а не квадратная: у квадратной
   * (max по осям) спад повторяет прямоугольник и вокруг кнопки становится
   * виден светлый прямоугольник с мягкими углами. Эллипс обнуляет свет на
   * серединах кромок и заодно рассеивает ударную волну к краю.
   */
  col *= 1.0 - smoothstep(0.45, 1.0, length(vUv * 2.0 - 1.0));

  /*
   * col уже и есть вклад света, сложенный из слагаемых, — это готовый
   * премультиплицированный цвет. Домножать его на альфу ещё раз (как делают
   * фоны, где col — цвет, а a — покрытие) нельзя: спад гаснет квадратично,
   * и весь ореол за кромкой диска уходит в чёрный.
   */
  float a = clamp(max(max(col.r, col.g), col.b), 0.0, 1.0);
  gl_FragColor = vec4(col, a);
}`
